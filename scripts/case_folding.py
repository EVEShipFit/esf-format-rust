"""Writes src/fold_table.rs from the Unicode CaseFolding.txt: python3 scripts/case_folding.py"""

import pathlib
import urllib.request

URL = "https://www.unicode.org/Public/UCD/latest/ucd/CaseFolding.txt"

with urllib.request.urlopen(URL) as response:
    lines = response.read().decode().splitlines()

version = lines[0].removeprefix("# CaseFolding-").removesuffix(".txt")
pairs = []
for line in lines:
    fields = [f.strip() for f in line.split("#")[0].split(";")]
    if len(fields) < 3 or fields[1] not in ("C", "S"):
        continue
    code, folded = int(fields[0], 16), int(fields[2], 16)
    if code > 0x7F:
        pairs.append(f"    ('\\u{{{code:X}}}', '\\u{{{folded:X}}}'),\n")

out = pathlib.Path(__file__).parent.parent / "src" / "fold_table.rs"
out.write_text(
    f"// Generated by scripts/case_folding.py from Unicode {version} CaseFolding.txt.\n\n"
    "/// Unicode simple case folding of every non-ASCII character that has one, by character.\n"
    "#[rustfmt::skip]\n"
    "pub(crate) const FOLDS: &[(char, char)] = &[\n" + "".join(pairs) + "];\n"
)
